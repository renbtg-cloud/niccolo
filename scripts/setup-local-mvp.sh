#!/usr/bin/env bash
# One-command first-user orchestrator: bootstrap if needed, configure a model if
# needed, then start the local MVP. It deliberately delegates secret handling
# to the focused helpers instead of copying credentials between steps.
set -Eeuo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

usage(){
  cat <<'USAGE'
Usage:
  bash scripts/setup-local-mvp.sh [--no-browser]

On a fresh interactive installation this runs bootstrap, private model
configuration, and local startup in sequence. On later runs it reuses the
existing private local state and starts Niccolò directly.
USAGE
}

case "${1:-}" in
  --help|-h) usage; exit 0 ;;
  ''|--no-browser) ;;
  *) usage >&2; exit 2 ;;
esac

bootstrap_files=(
  .niccolo-local/local.env
  .niccolo-local/identifiers.txt
  .niccolo-local/token.txt
)
present=0
for file in "${bootstrap_files[@]}"; do
  [[ -s "$file" ]] && ((present+=1)) || true
done

if (( present == 0 )); then
  echo 'Local bootstrap: not found; starting first-run bootstrap.'
  bash scripts/bootstrap-local-mvp.sh
elif (( present != ${#bootstrap_files[@]} )); then
  echo 'Local bootstrap is incomplete; refusing to overwrite partial private state.' >&2
  printf 'Expected: %s\n' "${bootstrap_files[*]}" >&2
  echo 'Inspect or remove the incomplete .niccolo-local directory before retrying.' >&2
  exit 2
else
  echo 'Local bootstrap: existing private state found.'
fi

# If any explicit model setting was supplied for this invocation, treat the
# explicit environment as authoritative. Do not silently fall back to a stored
# endpoint/key when an operator is trying to override it.
explicit_model_env=0
for name in NICCOLO_LLM_BASE_URL NICCOLO_LLM_MODEL NICCOLO_LLM_API_KEY NICCOLO_LLM_PROVIDER NICCOLO_LLM_JSON_MODE; do
  [[ -z "${!name+x}" ]] || explicit_model_env=1
done

model_ready_from_environment(){
  local base="${NICCOLO_LLM_BASE_URL:-}" model="${NICCOLO_LLM_MODEL:-}" key="${NICCOLO_LLM_API_KEY:-}"
  [[ -n "$base" && -n "$model" ]] || return 1
  [[ "$base" != https://* || -n "$key" ]] || return 1
  return 0
}

model_ready_from_private_file(){
  local file='.niccolo-local/model.env'
  [[ -s "$file" ]] || return 1
  (
    unset NICCOLO_LLM_BASE_URL NICCOLO_LLM_MODEL NICCOLO_LLM_API_KEY NICCOLO_LLM_PROVIDER NICCOLO_LLM_JSON_MODE
    # Generated by configure-local-model.sh with shell-escaped values only.
    # shellcheck disable=SC1090
    source "$file"
    model_ready_from_environment
  )
}

if (( explicit_model_env == 1 )); then
  if ! model_ready_from_environment; then
    echo 'Explicit NICCOLO_LLM_* override is incomplete; refusing to mix it with stored model credentials.' >&2
    exit 2
  fi
  echo 'Reasoning model: using explicit process configuration.'
elif model_ready_from_private_file; then
  echo 'Reasoning model: existing private configuration found.'
else
  if [[ -t 0 ]]; then
    echo 'Reasoning model: not configured; starting private configuration.'
    bash scripts/configure-local-model.sh
  else
    echo 'Reasoning model is not configured and this session is non-interactive.' >&2
    echo 'Run: bash scripts/configure-local-model.sh' >&2
    echo 'Or export complete NICCOLO_LLM_* settings before setup.' >&2
    exit 2
  fi
fi

echo 'Starting Niccolò.'
exec bash scripts/start-local-mvp.sh ${1:+"$1"}
